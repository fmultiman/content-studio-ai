// VEO_KLING_FIRST_LAST_FRAME_V1
//
// Google Veo capabilities are CODE-BACKED (like Kling REST): they describe exactly what the executing client
// (lib/providers/gemini/veo-client.ts) sends, taken from Google's Gemini API Veo documentation
// (ai.google.dev/gemini-api/docs/veo). Changing this file without changing the client is a bug.
//
// What is deliberately NOT offered, even though the documentation lists it: video extension, reference images
// ("referenceImages" guide identity/style — a different capability from first/last frame), 4K on Lite (not
// supported by Google), seed, negative prompt and person-generation overrides (provider defaults stay in force; none of
// them is a product control). Audio is always generated by Veo and has no switch, so `audio` is false (nothing is sent)
// and `nativeAudio` lets the UI say so.
//
// Provider rules encoded here (Google's documentation):
//   - durations 4 / 6 / 8 s; 1080p and 4k require 8 s (`durationsByResolution`);
//   - aspect ratio 16:9 or 9:16, for text and image input alike;
//   - resolution 720p / 1080p; 4k on Veo 3.1 and Veo 3.1 Fast only;
//   - first + last frame: `image` + `lastFrame` in the same instance (`lastFrame` is only valid together with `image`).
//     The current page states no duration/resolution/audio restriction for first+last frame, but earlier revisions required
//     8 s for interpolation and the page is internally inconsistent about the other 8 s rules. Until a paid canary proves
//     otherwise, A+B is restricted CONSERVATIVELY to 8 s (UI and server; `lastFrame.requiresDuration`).

import type { VideoModelCapability, VideoOperationCapability } from './capabilities'

export const VEO_MODEL_STANDARD = 'veo-3.1-generate-preview'
export const VEO_MODEL_FAST = 'veo-3.1-fast-generate-preview'
export const VEO_MODEL_LITE = 'veo-3.1-lite-generate-preview'

const BASE_DURATIONS = [4, 6, 8]
const EIGHT_SECONDS_ONLY = [8]

function veoModel(id: string, label: string, resolutions: VideoModelCapability['resolutions'], withLastFrame: boolean): VideoModelCapability {
  return {
    id,
    label,
    durations: [...BASE_DURATIONS],
    resolutions: [...resolutions],
    aspectRatios: ['16:9', '9:16'],
    audio: false,
    nativeAudio: true,
    multiShot: false,
    asmr: false,
    audioPrompt: false,
    musicPrompt: false,
    durationsByResolution: resolutions.includes('4k')
      ? { '1080p': [...EIGHT_SECONDS_ONLY], '4k': [...EIGHT_SECONDS_ONLY] }
      : { '1080p': [...EIGHT_SECONDS_ONLY] },
    ...(withLastFrame ? { lastFrame: { audioAllowed: true, multiShotAllowed: true, requiresDuration: 8 } } : {}),
  }
}

const TEXT_MODELS = (): VideoModelCapability[] => [
  veoModel(VEO_MODEL_STANDARD, 'Veo 3.1', ['720p', '1080p', '4k'], false),
  veoModel(VEO_MODEL_FAST, 'Veo 3.1 Fast', ['720p', '1080p', '4k'], false),
  veoModel(VEO_MODEL_LITE, 'Veo 3.1 Lite', ['720p', '1080p'], false),
]

const IMAGE_MODELS = (): VideoModelCapability[] => [
  veoModel(VEO_MODEL_STANDARD, 'Veo 3.1', ['720p', '1080p', '4k'], true),
  veoModel(VEO_MODEL_FAST, 'Veo 3.1 Fast', ['720p', '1080p', '4k'], true),
  veoModel(VEO_MODEL_LITE, 'Veo 3.1 Lite', ['720p', '1080p'], true),
]

export function veoVideoOperations(): VideoOperationCapability[] {
  return [
    { operation: 'image_to_video', models: IMAGE_MODELS() },
    { operation: 'text_to_video', models: TEXT_MODELS() },
  ]
}

export const VEO_MODEL_IDS: readonly string[] = [VEO_MODEL_STANDARD, VEO_MODEL_FAST, VEO_MODEL_LITE]
