#!/usr/bin/env node
/**
 * Phase 2I-A1 — generates infra/render-worker-runtime/fixtures/canonical-input.json.
 *
 * This is an OFFLINE tool, not part of the worker's runtime boundary: the
 * worker itself never calls `resolveTimelineManifest` (its scope starts
 * from an already-resolved `ResolvedTimelineInput` — see README.md). This
 * script runs the real, unmodified `resolveTimelineManifest` once, against
 * a minimal manifest shaped exactly like the real product path (one
 * `editorial.documentary-card` "cover" segment with a `library_file` hero
 * asset, matching Phase 2G-C/2G-D's proven manifests), so the fixture is
 * guaranteed structurally correct rather than hand-typed. The neutral
 * resolver leaves a `library_file` asset's `url` empty by design (see
 * lib/creative/assets/resolve-asset.ts) — this script then patches in a
 * clearly-fake placeholder URL, exactly mirroring what
 * `patchResolvedTimelineAssets` does in the real product preparation path,
 * without needing a real LibraryFile/S3 lookup.
 *
 * Usage: node infra/render-worker-runtime/generate-fixture.mjs
 */
import { createJiti } from 'jiti'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..', '..')
const jiti = createJiti(import.meta.url, { alias: { '@': repoRoot }, jsx: true })

const { resolveTimelineManifest } = await jiti.import('../../lib/creative/resolution/resolve-timeline.ts', { default: false })

const manifest = {
  schema_version: 'timeline.v0',
  manifest_id: 'worker-proof:timeline:documentary-card:cover-a',
  context: {
    project_ref: 'fixture:project:comunidades-alternativas',
    production_ref: 'fixture:production:terra-una-reel',
  },
  specification: { width: 1080, height: 1920, fps: 30, duration_frames: 90 },
  identity: { snapshot_ref: 'fixture:identity:comunidades-alternativas:v1', token_profile: 'default' },
  tracks: [{ id: 'visual-main', kind: 'video', order: 0 }],
  segments: [{
    id: 'cover-main',
    track_id: 'visual-main',
    start_frame: 0,
    duration_frames: 90,
    kind: 'template',
    payload: {
      template: { id: 'editorial.documentary-card', version: '0.1.0', variant: 'cover', scope: 'system' },
      content: {
        eyebrow: 'Content Studio render worker',
        title: 'VPS proof: canonical timeline input',
        subtitle: 'Generated by infra/render-worker-runtime/generate-fixture.mjs — see README.md before use.',
        source_line: 'Phase 2I-A1',
        detail_note: 'hero.url below is a placeholder; replace with a real reachable asset URL before rendering.',
      },
      assets: { hero: { type: 'library_file', ref: 'REPLACE-WITH-REAL-LIBRARY-FILE-ID', fit: 'cover' } },
      sequence: { index: 1, total: 1 },
      motion: { preset: 'none' },
    },
  }],
  assets: {},
  render_intent: { purpose: 'preview', container: 'mp4', audio: false, captions: 'none' },
}

const resolved = resolveTimelineManifest(manifest)
if (!resolved.valid) {
  console.error('[generate-fixture] resolveTimelineManifest failed:', JSON.stringify(resolved.errors, null, 2))
  process.exit(1)
}

const PLACEHOLDER_URL = 'https://REPLACE-WITH-A-REAL-REACHABLE-IMAGE-URL/example.png'

const patched = {
  ...resolved.value,
  resolvedTemplateSegments: resolved.value.resolvedTemplateSegments.map((entry) => ({
    ...entry,
    resolvedAssets: {
      ...entry.resolvedAssets,
      hero: entry.resolvedAssets.hero
        ? {
            ...entry.resolvedAssets.hero,
            url: PLACEHOLDER_URL,
            mime_type: 'image/png',
          }
        : entry.resolvedAssets.hero,
    },
  })),
}

const outDir = path.join(here, 'fixtures')
await mkdir(outDir, { recursive: true })
const outPath = path.join(outDir, 'canonical-input.json')
await writeFile(outPath, `${JSON.stringify(patched, null, 2)}\n`, 'utf8')

console.log(`[generate-fixture] Wrote ${path.relative(repoRoot, outPath)}`)
console.log('[generate-fixture] hero.url is a documented placeholder — the human operator must replace it')
console.log('[generate-fixture] with a real reachable image URL before using this fixture as a live proof input.')
